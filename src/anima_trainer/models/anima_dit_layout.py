def anima_dit_tensors() -> dict[str, tuple[int, ...]]:
    """Every tensor name of the DiT with its shape."""
    blocks = {
        f"blocks.{block}.{name}": shape
        for block in range(ANIMA_BLOCKS)
        for name, shape in BLOCK_TENSORS.items()
    }
    return {**blocks, **OUTSIDE_TENSORS}
