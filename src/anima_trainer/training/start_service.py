"""The checks of Citron's start_training() before launch, without running anything.

Like Citron, Start uses the configs generated by the last Configure (or a custom training
config) together with the GPU, CPU threads and base model currently chosen in the form.
"""

from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import toml

from anima_trainer.runtime.paths import RuntimePaths
from anima_trainer.settings.schema import TrainingSettings
from anima_trainer.training.command_builder import LaunchSpec, build_training_launch
from anima_trainer.training.runner import log_file_path

PREVIEWS_NOTE = "INFO: Previews on: images in <output_dir>/sample/ during training."


@dataclass(frozen=True)
class StartRequest:
    gpu_index: str
    cpu_threads: int
    base_model: str
    custom_config: str = ""


@dataclass(frozen=True)
class StartPlan:
    messages: tuple[str, ...]
    spec: LaunchSpec | None = None
    log_path: Path | None = None

    @property
    def success(self) -> bool:
        return self.spec is not None and self.log_path is not None


def plan_start(
    saved: TrainingSettings, paths: RuntimePaths, request: StartRequest, now: datetime
) -> StartPlan:
    """What to launch for `request`, or the Citron error messages explaining why not."""
    custom = request.custom_config.strip()
    train_config = custom or saved.last_train_config
    dataset_config = saved.last_dataset_config
    error = _config_error(paths, train_config, dataset_config)
    if error:
        return StartPlan((f"ERROR: {error}",))
    if not paths.train_script.exists():
        script = paths.train_script
        return StartPlan((f"ERROR: Training script not found: {script}. Run setup first.",))

    # Passed verbatim: accelerate runs from the data folder, like Citron's own command.
    with_previews = has_previews(paths.resolve(train_config))
    spec = build_training_launch(
        paths,
        Path(train_config),
        Path(dataset_config),
        request.gpu_index,
        request.cpu_threads,
        with_previews,
    )
    previews = (PREVIEWS_NOTE,) if with_previews else ()
    messages = (
        f"Using GPU index: {request.gpu_index}",
        *previews,
        f"Command: {spec.display()}",
        "",
    )
    log_path = log_file_path(paths.logs_dir, saved.project_name or "run", now)
    return StartPlan(messages, spec, log_path)


def _config_error(paths: RuntimePaths, train_config: str, dataset_config: str) -> str | None:
    if not train_config:
        return "No training config found. Run 'Configure Training' first, or provide a config path."
    if not paths.resolve(train_config).exists():
        return f"Training config not found: {train_config}"
    if not dataset_config:
        return "No dataset config found. Run 'Configure Training' first."
    if not paths.resolve(dataset_config).exists():
        return f"Dataset config not found: {dataset_config}"
    return None


def has_previews(train_config: Path) -> bool:
    """True when the training config asks sd-scripts for preview images.

    Read from the file, so a custom config with sample_prompts gets the preview launcher too;
    a config that cannot be parsed runs sd-scripts directly, which then reports the problem.
    """
    try:
        return "sample_prompts" in toml.loads(train_config.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, toml.TomlDecodeError):
        return False
